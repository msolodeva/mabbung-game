async page => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.reload();
  await page.waitForFunction(() => !!window.game);
  await page.getByRole('button', {name:'트레이닝', exact:true}).click();
  await page.keyboard.press('f');
  await page.waitForFunction(() => window.game.scene === 'FIGHTING');
  await page.keyboard.press('F4');
  await page.keyboard.press('F7');
  const frame = await page.evaluate(() => window.game.simulationFrames);
  await page.keyboard.press('F8');
  await page.waitForFunction(n => window.game.simulationFrames === n + 1, frame);
  await page.keyboard.press('F7');
  await page.keyboard.press('r');
  await page.waitForFunction(() => window.game.particles.superFreeze);
  await page.screenshot({path:'output/playwright/final-super.png'});
  await page.waitForFunction(() => window.game.p2.lastDamage > 0);
  await page.keyboard.press('Escape');
  if (!await page.evaluate(() => window.game.menu.isPaused)) throw new Error('Pause failed');
  await page.keyboard.press('Escape');
  await page.keyboard.press('F4');
  await page.keyboard.press('h');
  await page.waitForFunction(() => window.game.p1.moveId === 'fireball');
  if (await page.evaluate(() => window.game.menu.showGuide || window.game.debugHitboxes)) throw new Error('Combat keys toggle UI');
  await page.waitForFunction(() => window.game.p1.neutral);
  await page.keyboard.press('F4');
  await page.keyboard.down('d');
  await page.waitForFunction(() => window.game.p1.x > 760);
  await page.keyboard.up('d');
  await page.keyboard.press('g');
  await page.waitForFunction(() => window.game.p2.lastDamage > 0);
  await page.screenshot({path:'output/playwright/final-hit.png'});
  await page.getByRole('button', {name:'2인 대전', exact:true}).click();
  await page.keyboard.press('f');
  await page.keyboard.press('Enter');
  await page.waitForFunction(() => window.game.scene === 'FIGHTING');
  // Set up a final-round lethal strike; damage and scene changes still use the real game loop.
  await page.evaluate(() => {const g=window.game;g.p1.x=700;g.p2.x=810;g.p2.hp=1;g.p1.wins=1;});
  await page.keyboard.press('f');
  await page.waitForFunction(() => window.game.scene === 'ROUND_END');
  await page.screenshot({path:'output/playwright/final-ko.png'});
  await page.waitForFunction(() => window.game.scene === 'MATCH_END' && window.game.stateTimer > 40);
  if (!await page.evaluate(() => window.game.matchWinner === 1)) throw new Error('Winner incorrect');
  await page.keyboard.press('f');
  await page.waitForFunction(() => window.game.scene === 'TITLE');
  await page.setViewportSize({width:390,height:844});
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Mobile horizontal overflow');
  await page.screenshot({path:'output/playwright/final-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1060});
  await page.screenshot({path:'output/playwright/final-title.png'});
  if (errors.length) throw new Error(errors.join('\n'));
}
